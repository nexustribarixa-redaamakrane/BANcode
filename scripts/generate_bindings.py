def generate_python(registry):
    py_dir = ROOT / "python" / "bancode"
    py_dir.mkdir(parents=True, exist_ok=True)

    slots = registry["slots"]
    assigned = [s for s in slots if s["assigned"]]
    categories = registry["categories"]

    # --- __init__.py ---
    init = []
    init.append('"""BANcode Framework - Python bindings"""')
    init.append("")
    init.append("from bancode.registry import BANcodeRegistry")
    for cat in categories:
        init.append(f"from bancode.{cat} import {ENUM_NAMES[cat]}")
    init.append("")
    init.append("__all__ = [")
    init.append('    "BANcodeRegistry",')
    for cat in categories:
        init.append(f'    "{ENUM_NAMES[cat]}",')
    init.append("]")
    init.append("")

    with open(py_dir / "__init__.py", "w", encoding="utf-8") as f:
        f.write("\n".join(init) + "\n")

    # --- Per-category enums ---
    for cat, meta in categories.items():
        cat_slots = [s for s in slots if s["category"] == cat and s["assigned"]]
        enum_name = ENUM_NAMES[cat]

        ce = []
        ce.append(f'"""BANcode {cat} codes"""')
        ce.append("")
        ce.append("from enum import IntEnum")
        ce.append("")
        ce.append(f"class {enum_name}(IntEnum):")
        ce.append(f'    """{meta.get("role", "")}"""')
        ce.append("")
        seen_names = set()
        for s in cat_slots:
            if s["name"] in seen_names:
                continue
            seen_names.add(s["name"])
            ce.append(f'    {s["name"]} = 0x{s["hex"]}')
        ce.append("")
        ce.append("    @classmethod")
        ce.append("    def from_value(cls, val):")
        ce.append("        try:")
        ce.append("            return cls(val)")
        ce.append("        except ValueError:")
        ce.append("            return None")
        ce.append("")

        with open(py_dir / f"{cat}.py", "w", encoding="utf-8") as f:
            f.write("\n".join(ce) + "\n")

    # --- registry.py ---
    reg = []
    reg.append('"""BANcode master registry lookup."""')
    reg.append("")
    reg.append("from dataclasses import dataclass")
    reg.append("from typing import Optional")
    for cat in categories:
        reg.append(f"from bancode.{cat} import {ENUM_NAMES[cat]}")
    reg.append("")
    reg.append("")
    reg.append("@dataclass")
    reg.append("class CodeEntry:")
    reg.append('    """Complete metadata for a single BANcode."""')
    reg.append("    hex_value: str")
    reg.append("    value: int")
    reg.append("    name: str")
    reg.append("    category: str")
    reg.append("    subcategory: str")
    reg.append("    description: str")
    reg.append("")
    reg.append("")
    reg.append("class BANcodeRegistry:")
    reg.append('    """Singleton registry for all BANcode codes."""')
    reg.append("")
    reg.append("    _instance = None")
    reg.append("    _codes = {}")
    reg.append("")
    reg.append("    def __new__(cls):")
    reg.append("        if cls._instance is None:")
    reg.append("            cls._instance = super().__new__(cls)")
    reg.append("            cls._instance._load()")
    reg.append("        return cls._instance")
    reg.append("")
    reg.append("    def _load(self):")
    reg.append("        codes = {")
    for s in assigned:
        desc = s["description"].replace('"', '\\"')
        reg.append(f'            0x{s["hex"]}: CodeEntry(')
        reg.append(f'                hex_value="0x{s["hex"]}",')
        reg.append(f'                value=0x{s["hex"]},')
        reg.append(f'                name="{s["name"]}",')
        reg.append(f'                category="{s["category"]}",')
        reg.append(f'                subcategory="{s["subcategory"]}",')
        reg.append(f'                description="{desc}",')
        reg.append(f'            ),')
    reg.append("        }")
    reg.append("        self._codes = codes")
    reg.append("")
    reg.append("    def lookup(self, code):")
    reg.append('        """Look up a code by int value. Returns CodeEntry or None."""')
    reg.append("        return self._codes.get(code)")
    reg.append("")
    reg.append("    def name(self, code):")
    reg.append('        """Return codename string or \'UNKNOWN\'."""')
    reg.append("        entry = self._codes.get(code)")
    reg.append('        return entry.name if entry else "UNKNOWN"')
    reg.append("")
    reg.append("    def is_valid(self, code):")
    reg.append('        """Return True if code is a known BANcode."""')
    reg.append("        return code in self._codes")
    reg.append("")
    reg.append("    @property")
    reg.append("    def all_codes(self):")
    reg.append("        return list(self._codes.values())")

    with open(py_dir / "registry.py", "w", encoding="utf-8") as f:
        f.write("\n".join(reg) + "\n")

    print(f"Generated Python package in {py_dir}")
    print(f"  {len(assigned)} codes across {len(categories)} enums")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    registry = load_registry()
    generate_c99(registry)
    generate_rust(registry)
    generate_python(registry)
    print("All bindings generated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
