def generate_rust(registry):
    rust_dir = ROOT / "rust_bindings"
    src_dir = rust_dir / "src"
    src_dir.mkdir(parents=True, exist_ok=True)

    slots = registry["slots"]
    assigned = [s for s in slots if s["assigned"]]
    categories = registry["categories"]

    # --- lib.rs ---
    rs = []
    rs.append("//! BANcode Framework - Rust bindings")
    rs.append("//! AUTO-GENERATED by generate_bindings.py - DO NOT EDIT")
    rs.append("")
    rs.append("#![no_std]")
    rs.append("")
    rs.append("use core::fmt;")
    rs.append("")

    # Per-category enums
    for cat, meta in categories.items():
        cat_slots = [s for s in slots if s["category"] == cat and s["assigned"]]
        enum_name = ENUM_NAMES[cat]
        seen_names = set()
        unique_slots = []
        for s in cat_slots:
            if s["name"] not in seen_names:
                seen_names.add(s["name"])
                unique_slots.append(s)

        rs.append(f"/// {meta.get('role', '')}")
        rs.append(f"/// Range: 0x{meta['block_start']} - 0x{meta['block_end']}")
        rs.append(f"#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]")
        rs.append(f"#[repr(u32)]")
        rs.append(f"pub enum {enum_name} {{")
        for s in unique_slots:
            variant = s["name"]
            rs.append(f"    {variant} = 0x{s['hex']},")
        rs.append("}")
        rs.append("")

        # Display impl
        rs.append(f"impl fmt::Display for {enum_name} {{")
        rs.append(f"    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{")
        rs.append(f"        match *self {{")
        for s in unique_slots:
            rs.append(f"            {enum_name}::{s['name']} => write!(f, \"0x{s['hex']}: {s['name']}\"),")
        rs.append(f"        }}")
        rs.append(f"    }}")
        rs.append(f"}}")
        rs.append("")

        # TryFrom<u32>
        rs.append(f"impl TryFrom<u32> for {enum_name} {{")
        rs.append(f"    type Error = u32;")
        rs.append(f"    fn try_from(v: u32) -> Result<Self, u32> {{")
        rs.append(f"    match v {{")
        for s in unique_slots:
            rs.append(f"            0x{s['hex']} => Ok({enum_name}::{s['name']}),")
        rs.append(f"            _ => Err(v),")
        rs.append(f"        }}")
        rs.append(f"    }}")
        rs.append(f"}}")
        rs.append("")

    # Master enum
    rs.append("/// All BANcode diagnostic codes")
    rs.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]")
    rs.append("#[repr(u32)]")
    rs.append("pub enum BANcode {")
    seen_names = set()
    unique_assigned = []
    for s in assigned:
        if s["name"] not in seen_names:
            seen_names.add(s["name"])
            unique_assigned.append(s)
            rs.append(f"    {s['name']} = 0x{s['hex']},")
    rs.append("}")
    rs.append("")

    # Display for master
    rs.append("impl fmt::Display for BANcode {")
    rs.append("    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {")
    rs.append("    match *self {")
    for s in unique_assigned:
        rs.append(f"            BANcode::{s['name']} => write!(f, \"0x{s['hex']}: {s['name']}\"),")
    rs.append("        }")
    rs.append("    }")
    rs.append("}")
    rs.append("")

    # TryFrom for master
    rs.append("impl TryFrom<u32> for BANcode {")
    rs.append("    type Error = u32;")
    rs.append("    fn try_from(v: u32) -> Result<Self, u32> {")
    rs.append("        match v {")
    for s in unique_assigned:
        rs.append(f"            0x{s['hex']} => Ok(BANcode::{s['name']}),")
    rs.append("            _ => Err(v),")
    rs.append("        }")
    rs.append("    }")
    rs.append("}")
    rs.append("")

    # Lookup functions
    rs.append("/// Returns true if code is a known BANcode")
    rs.append("pub fn is_valid(code: u32) -> bool {")
    rs.append("    BANcode::try_from(code).is_ok()")
    rs.append("}")
    rs.append("")
    rs.append("/// Returns codename string if known")
    rs.append("pub fn name(code: u32) -> Option<&'static str> {")
    rs.append("    match code {")
    for s in assigned:
        rs.append(f"        0x{s['hex']} => Some(\"{s['name']}\"),")
    rs.append("        _ => None,")
    rs.append("    }")
    rs.append("}")

    with open(src_dir / "lib.rs", "w", encoding="utf-8") as f:
        f.write("\n".join(rs) + "\n")

    # --- Cargo.toml ---
    cargo = []
    cargo.append("[package]")
    cargo.append('name = "bancode"')
    cargo.append('version = "0.1.0"')
    cargo.append('edition = "2026"')
    cargo.append('description = "BANcode Framework - diagnostic code bindings"')
    cargo.append("")
    cargo.append("[lib]")
    cargo.append('name = "bancode"')
    cargo.append('path = "src/lib.rs"')

    with open(rust_dir / "Cargo.toml", "w", encoding="utf-8") as f:
        f.write("\n".join(cargo) + "\n")

    print(f"Generated Rust crate in {rust_dir}")
    print(f"  {len(assigned)} codes across {len(categories)} enums")


