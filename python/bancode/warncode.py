"""BANcode warncode codes"""

from enum import IntEnum

class WARNcode(IntEnum):
    """Non-fatal telemetry; threshold alerts, degraded performance, predictive maintenance. May be printable; useful when showing the glyph of the error, not just its codename or codepoint."""

    SUCS_MODE_INVALID = 0x0011A800
    SUCS_MODE_ALREADY_ACTIVE = 0x0011A801
    SUCS_PLUGIN_INVALID_BLOB = 0x0011A802
    SUCS_PLUGIN_DUPLICATE_ID = 0x0011A803
    SUCS_PLUGIN_STAGING_FULL = 0x0011A804
    SUCS_PLUGIN_NOT_OWFS = 0x0011A805
    SUCS_PLUGIN_MOUNT_FAILED = 0x0011A806
    SUCS_PLUGIN_BUFFER_OVERFLOW = 0x0011A807
    SUCS_PLUGIN_RANGE_COLLISION = 0x0011A808
    SUCS_PLUGIN_CHECKSUM_MISMATCH = 0x0011A809
    SUCS_KEY_INVALID = 0x0011A80A
    OWFS_VOLUME_DIRTY = 0x0011A900
    OWFS_VOLUME_LOCKED = 0x0011A901
    OWFS_WRITE_PROTECTED = 0x0011A902
    OWFS_NO_FREE_BLOCKS = 0x0011A903
    OWFS_NO_FREE_INODES = 0x0011A904
    OWFS_CATALOG_FULL = 0x0011A905
    OWFS_ACCESS_DENIED = 0x0011A906
    OWFS_KEY_INVALID = 0x0011A907
    OWFS_CRC_SILENT_SKIP = 0x0011A908
    USFS_VOLUME_DIRTY = 0x0011AA00
    USFS_VOLUME_LOCKED = 0x0011AA01
    USFS_WRITE_PROTECTED = 0x0011AA02
    USFS_NO_FREE_BLOCKS = 0x0011AA03
    USFS_NO_FREE_ENTRIES = 0x0011AA04
    USFS_ACCESS_DENIED = 0x0011AA05
    USFS_KEY_INVALID = 0x0011AA06
    USFS_ENCRYPTED_UNHANDLED = 0x0011AA07
    MBL_NO_GOP = 0x0011AB00
    MBL_NO_BLOCK_IO = 0x0011AB01
    MBL_NO_LOADED_IMAGE = 0x0011AB02
    MBL_GOP_MODE_FAIL = 0x0011AB03
    MBL_REMOVABLE_MEDIA = 0x0011AB04
    MBL_MEDIA_NOT_PRESENT = 0x0011AB05
    MBL_OWMKFS_REBOOT_REQUIRED = 0x0011AB06
    MBL_PLUGIN_REBOOT_REQUIRED = 0x0011AB07
    MBL_RTC_UNAVAILABLE = 0x0011AB08
    MBL_KBD_UNAVAILABLE = 0x0011AB09
    MBL_MENU_EMPTY = 0x0011AB0A
    MBL_SUTF8_NONASCII = 0x0011AB0B

    @classmethod
    def from_value(cls, val):
        try:
            return cls(val)
        except ValueError:
            return None

